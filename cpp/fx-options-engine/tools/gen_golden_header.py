#!/usr/bin/env python3
"""Generate tests/golden_vectors.hpp from the golden JSON.

The JSON (python/fx/01-options-pricing/tests/golden/golden_vectors.json)
holds mpmath reference values with a per-output absolute tolerance. This
script emits them as a constexpr array for the GoogleTest suite. Doubles
are written with Python's shortest round-trip ``repr``, so the header
carries the JSON values exactly.

Usage:
    python3 tools/gen_golden_header.py [--check] [json_path] [header_path]

``--check`` exits 1 if the committed header differs from what the JSON
generates (CI uses it to prove provenance).
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_JSON = HERE.parents[2] / "python/fx/01-options-pricing/tests/golden/golden_vectors.json"
DEFAULT_HEADER = HERE.parent / "tests/golden_vectors.hpp"
NS = "fxopt"
GUARD = "FXOPT_TESTS_GOLDEN_VECTORS_HPP"
MAX_IN = 7
MAX_OUT = 12


def fmt(x: float) -> str:
    """Shortest decimal that round-trips to the same IEEE-754 double."""
    if math.isinf(x):
        return "std::numeric_limits<double>::infinity()"
    s = repr(float(x))
    return s if any(c in s for c in ".eE") else s + ".0"


def render(data: dict) -> str:
    recs = data["records"]
    lines = [
        "// AUTO-GENERATED by tools/gen_golden_header.py; do not edit.",
        "// Source: " + data["generator"] + " (" + data["oracle"] + ")",
        "",
        f"#ifndef {GUARD}",
        f"#define {GUARD}",
        "",
        "#include <array>",
        "#include <limits>",
        "",
        f'#include "{NS}/black_scholes.hpp"' if NS == "eqopt" else f'#include "{NS}/common.hpp"',
        "",
        f"namespace {NS}::golden {{",
        "",
        "struct GoldenOut {",
        "    const char* name;",
        "    double value;",
        "    double tol;  // absolute tolerance from the JSON tolerance rules",
        "};",
        "",
        "struct GoldenRecord {",
        "    const char* fn;  // inputs in the order of the JSON schema for fn",
        f"    std::array<double, {MAX_IN}> in;",
        f"    {NS}::OptionType type;",
        "    int flag;",
        "    int n_out;",
        f"    std::array<GoldenOut, {MAX_OUT}> out;",
        "};",
        "",
        f"inline constexpr std::array<GoldenRecord, {len(recs)}> kRecords = {{{{",
    ]
    for r in recs:
        ins = list(r["in"]) + [0.0] * (MAX_IN - len(r["in"]))
        outs = [f'{{"{k}", {fmt(v[0])}, {fmt(v[1])}}}' for k, v in r["out"].items()]
        outs += ['{"", 0.0, 0.0}'] * (MAX_OUT - len(outs))
        ot = f"{NS}::OptionType::Call" if r["type"] == "call" else f"{NS}::OptionType::Put"
        lines.append(f'    {{"{r["fn"]}", {{{", ".join(fmt(x) for x in ins)}}}, {ot}, {r["flag"]}, '
                     f'{len(r["out"])}, {{{{{", ".join(outs)}}}}}}},')
    lines += ["}};", "", f"}}  // namespace {NS}::golden", "", f"#endif  // {GUARD}", ""]
    return "\n".join(lines)


def main() -> int:
    check = "--check" in sys.argv[1:]
    args = [a for a in sys.argv[1:] if a != "--check"]
    json_path = Path(args[0]) if args else DEFAULT_JSON
    header = Path(args[1]) if len(args) > 1 else DEFAULT_HEADER
    data = json.loads(json_path.read_text())
    if len(data["records"]) != data["n_records"]:
        raise SystemExit("n_records does not match the record list")
    text = render(data)
    if check:
        if not header.exists() or header.read_text() != text:
            print(f"STALE: {header} differs from the golden JSON; rerun without --check")
            return 1
        print(f"OK: {header} matches the golden JSON")
        return 0
    header.write_text(text)
    print(f"wrote {len(data['records'])} records to {header}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
