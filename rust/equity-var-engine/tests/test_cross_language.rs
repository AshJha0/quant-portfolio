/// Relative tolerance for cross-language agreement.
fn expect_rel(actual: f64, expected: f64, what: &str) {
    let tol = golden::TOL_REL * expected.abs() + golden::TOL_ABS;
    assert!(
        (actual - expected).abs() <= tol,
        "{what}: actual={actual} expected={expected} (tol={tol})"
    );
}

/// Case A input: `pnl[t] = 100 sin(3t + 1) + 0.5 t cos(t)`, `t = 0..99`.
fn case_a_pnl() -> Vec<f64> {
    (0..100)
        .map(|t| {
            let td = t as f64;
            100.0 * (3.0 * td + 1.0).sin() + 0.5 * td * td.cos()
        })
        .collect()
}

/// Case C input: `r[t, j] = 0.01 sin(t + j) + 0.005 cos(2t - j)`,
/// `t = 0..59`, `j = 0..2`.
fn case_c_returns() -> Matrix {
    let mut r = Matrix::zeros(60, 3);
    for t in 0..60 {
        for j in 0..3 {
            let (td, jd) = (t as f64, j as f64);
            let v = 0.01 * (td + jd).sin() + 0.005 * (2.0 * td - jd).cos();
            r.set(t, j, v);
        }
    }
    r
}

#[test]
fn case_a_historical_family() {
    let pnl = case_a_pnl();
    expect_rel(
        historical_var(&pnl, 0.01).unwrap(),
        golden::A_HIST_VAR_1PCT,
        "A hist VaR 1%",
    );
    expect_rel(
        historical_var(&pnl, 0.05).unwrap(),
        golden::A_HIST_VAR_5PCT,
        "A hist VaR 5%",
    );
    expect_rel(
        expected_shortfall(&pnl, 0.05).unwrap(),
        golden::A_ES_5PCT,
        "A ES 5%",
    );
    expect_rel(
        expected_shortfall(&pnl, 0.01).unwrap(),
        golden::A_ES_1PCT,
        "A ES 1%",
    );
    expect_rel(
        age_weighted_var(&pnl, 0.05, 0.98).unwrap(),
        golden::A_BRW_VAR_5PCT_LAM098,
        "A BRW VaR 5%",
    );
    expect_rel(
        filtered_historical_var(&pnl, 0.05, 0.94).unwrap(),
        golden::A_FHS_VAR_5PCT_LAM094,
        "A FHS VaR 5%",
    );
}

