//! Zero-dependency FX options pricing engine under Garman–Kohlhagen.
//!
//! Rust port of the Python reference project
//! `python/fx/01-options-pricing` (package `fx_options`) and sibling of the
//! C++ engine `cpp/fx-options-engine`, checked against golden vectors
//! computed in mpmath (see [`golden`]) and against the other engines on
//! seeded random inputs.
//!
//! # Conventions (used everywhere in this crate)
//!
//! * FX pairs are quoted **BASE/QUOTE**: EURUSD = number of USD per 1 EUR.
//! * `s` is the spot rate in domestic (quote) currency per unit of foreign
//!   (base) currency.  All option prices are in domestic currency per unit
//!   of foreign notional.
//! * `r_d` is the domestic (quote-currency) continuously compounded rate,
//!   `r_f` the foreign (base-currency) rate, both annualised, ACT/365F.
//!   Garman–Kohlhagen is Black–Scholes with the dividend yield `q = r_f`.
//! * `t` is time to expiry in years, `sigma` the annualised lognormal vol.
//! * Negative rates are legal (EUR/CHF era); negative `t` or `sigma` is not.
//! * Theta is per year; vega per unit of vol.
//!
//! Invalid inputs return [`FxError::InvalidInput`] (the mirror of the
//! Python `ValueError` contract): no panics on bad market data.
//!
//! # Quick example
//!
//! ```
//! use fx_options_engine::{gk_price, analytic_greeks, strike_from_delta,
//!                         DeltaConvention, OptionType};
//!
//! // EURUSD 6m call: S=1.10, K=1.12, r_d(USD)=4.25%, r_f(EUR)=2.90%, vol 9.25%
//! let px = gk_price(1.10, 1.12, 0.5, 0.0425, 0.0290, 0.0925,
//!                   OptionType::Call).unwrap();
//! assert!(px > 0.0 && px < 1.10);
//!
//! let g = analytic_greeks(1.10, 1.12, 0.5, 0.0425, 0.0290, 0.0925,
//!                         OptionType::Call).unwrap();
//! assert!((g.price - px).abs() < 1e-15);
//!
//! // 25-delta strike under the premium-adjusted spot convention (Brent
//! // solve on the market-standard high-strike branch):
//! let k25 = strike_from_delta(0.25, 1.10, 0.5, 0.0425, 0.0290, 0.0925,
//!                             OptionType::Call, DeltaConvention::SpotPa)
//!     .unwrap();
//! assert!(k25 > 1.10);
//! ```
