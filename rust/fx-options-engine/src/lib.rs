/// Option type; `phi(Call) = +1`, `phi(Put) = -1`.
///
/// A "call" is a call on the base (foreign) currency: the right to buy
/// one unit of base currency paying `K` units of quote currency.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum OptionType {
    /// Call on the base currency.
    Call,
    /// Put on the base currency.
    Put,
}

impl OptionType {
    /// Sign convention: `+1.0` for a call, `-1.0` for a put.
    ///
    /// ```
    /// use fx_options_engine::OptionType;
    /// assert_eq!(OptionType::Call.phi(), 1.0);
    /// assert_eq!(OptionType::Put.phi(), -1.0);
    /// ```
    #[inline]
    pub const fn phi(self) -> f64 {
        match self {
            OptionType::Call => 1.0,
            OptionType::Put => -1.0,
        }
    }

    /// The opposite option type (used by foreign–domestic symmetry).
    #[inline]
    pub const fn other(self) -> Self {
        match self {
            OptionType::Call => OptionType::Put,
            OptionType::Put => OptionType::Call,
        }
    }
}

impl fmt::Display for OptionType {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            OptionType::Call => "call",
            OptionType::Put => "put",
        })
    }
}

/// Error type for the engine: the mirror of the Python `ValueError`
/// contract (invalid inputs) plus explicit numerical-failure reporting.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FxError {
    /// An input violates the pricing preconditions (non-positive spot or
    /// strike, negative time or vol, non-finite value, arbitrage-violating
    /// price, out-of-range delta, ...).  Message identifies the offender.
    InvalidInput(String),
    /// A numerical routine failed (root not bracketed, no convergence).
    Numerical(String),
}

impl fmt::Display for FxError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            FxError::InvalidInput(msg) => write!(f, "invalid input: {msg}"),
            FxError::Numerical(msg) => write!(f, "numerical failure: {msg}"),
        }
    }
}

impl std::error::Error for FxError {}

/// Crate-wide result alias.
pub type FxResult<T> = Result<T, FxError>;

pub(crate) fn invalid<T>(msg: impl Into<String>) -> FxResult<T> {
    Err(FxError::InvalidInput(msg.into()))
}

/// Return `value`, or [`FxError::InvalidInput`] when a finite input
/// produced a non-finite result (a discount factor or forward overflowed).
pub(crate) fn finite_result(value: f64, what: &str) -> FxResult<f64> {
    if value.is_finite() {
        Ok(value)
    } else {
        invalid(format!(
            "{what}: result is not representable as a finite double              (a discount factor or forward overflows)"
        ))
    }
}

pub(crate) fn require_finite(value: f64, name: &str) -> FxResult<()> {
    if !value.is_finite() {
        return invalid(format!("{name} must be finite, got {value}"));
    }
    Ok(())
}

/// Validate common pricing inputs (mirror of the Python
/// `fx_options._common.validate_inputs`).
///
/// `s`, `k` must be positive and finite; `t >= 0`; `sigma >= 0`; rates
/// finite (negative rates are allowed).
pub(crate) fn validate_inputs(
    s: f64,
    k: f64,
    t: f64,
    r_d: f64,
    r_f: f64,
    sigma: f64,
) -> FxResult<()> {
    require_finite(s, "S")?;
    require_finite(k, "K")?;
    require_finite(t, "T")?;
    require_finite(r_d, "r_d")?;
    require_finite(r_f, "r_f")?;
    require_finite(sigma, "sigma")?;
    if s <= 0.0 {
        return invalid(format!("Spot S must be positive, got {s}"));
    }
    if k <= 0.0 {
        return invalid(format!("Strike K must be positive, got {k}"));
    }
    if t < 0.0 {
        return invalid(format!("Time to expiry T must be non-negative, got {t}"));
    }
    if sigma < 0.0 {
        return invalid(format!(
            "Volatility sigma must be non-negative, got {sigma}"
        ));
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// Normal distribution utilities (std-only, full double precision)
// ---------------------------------------------------------------------------

/// Standard normal PDF `n(x) = exp(-x^2/2) / sqrt(2 pi)`.
///
/// ```
/// let n0 = fx_options_engine::norm_pdf(0.0);
/// assert!((n0 - 0.3989422804014327).abs() < 1e-16);
/// ```
#[inline]
pub fn norm_pdf(x: f64) -> f64 {
    qp_core::special::norm_pdf(x)
}

/// Standard normal CDF `N(x)`, via Cody's rational-Chebyshev `erfc`
/// (~1e-16 relative accuracy, correct in both tails).
///
/// ```
/// use fx_options_engine::norm_cdf;
/// assert!((norm_cdf(0.0) - 0.5).abs() < 1e-16);
/// assert!((norm_cdf(1.959963984540054) - 0.975).abs() < 1e-12);
/// assert!((norm_cdf(-8.0) - 6.220960574271786e-16).abs() < 1e-27);
/// ```
#[inline]
pub fn norm_cdf(x: f64) -> f64 {
    qp_core::special::norm_cdf_c1_truncated(x)
}

/// Inverse standard normal CDF `N^{-1}(p)` for `p` in `(0, 1)`.
///
/// Acklam's rational approximation (~1.15e-9 relative) polished with two
/// Halley iterations against [`norm_cdf`] to full double precision
/// (~1e-15 absolute in `z`).  Returns `NaN` outside `(0, 1)`.
///
/// ```
/// use fx_options_engine::{norm_cdf, norm_ppf};
/// let z = norm_ppf(0.975);
/// assert!((z - 1.959963984540054).abs() < 1e-12);
/// assert!((norm_cdf(norm_ppf(1e-10)) - 1e-10).abs() < 1e-22);
/// assert!(norm_ppf(0.0).is_nan());
/// ```
pub fn norm_ppf(p: f64) -> f64 {
    if !(p > 0.0 && p < 1.0) {
        return f64::NAN;
    }
    let mut z = qp_core::special::acklam(p);
    for _ in 0..2 {
        z = qp_core::special::halley_step(z, p, norm_cdf(z), norm_pdf(z));
    }
    z
}

// ---------------------------------------------------------------------------
// Brent root finder (internal)
// ---------------------------------------------------------------------------

/// Brent's method mirroring `scipy.optimize.brentq` semantics: given
/// `f(a) f(b) <= 0`, returns a root to absolute x-tolerance `xtol`.
///
/// Returns [`FxError::Numerical`] if the initial bracket has no sign
/// change, or if `max_iter` iterations elapse without reaching `xtol`
/// (scipy raises in both cases; silently returning the last iterate
/// would let a non-converged strike or vol escape into a risk number).
pub(crate) fn brentq<F>(f: F, a: f64, b: f64, xtol: f64, max_iter: usize) -> FxResult<f64>
where
    F: Fn(f64) -> f64,
{
    qp_core::roots::brentq(f, a, b, xtol, max_iter).map_err(FxError::from)
}

impl From<qp_core::Error> for FxError {
    fn from(e: qp_core::Error) -> Self {
        match e {
            qp_core::Error::InvalidInput(m) => FxError::InvalidInput(m),
            qp_core::Error::Numerical(m) => FxError::Numerical(m),
        }
    }
}
