#!/usr/bin/env python3
"""Generate src/golden.rs from the golden JSON.

The JSON (python/equity/01-options-pricing/tests/golden/golden_vectors.json)
holds mpmath reference values with a per-output absolute tolerance. This
script emits them as a `pub const` array for the integration tests.
Doubles are written with Python's shortest round-trip ``repr``.

Usage:
    python3 tools/gen_golden_rs.py [--check] [json_path] [rs_path]

``--check`` exits 1 if the committed module differs from what the JSON
generates.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_JSON = HERE.parents[2] / "python/equity/01-options-pricing/tests/golden/golden_vectors.json"
DEFAULT_RS = HERE.parent / "src/golden.rs"
CRATE_TYPES = "use crate::black_scholes::OptionType;"
MAX_IN = 7


def fmt(x: float) -> str:
    """Shortest decimal that round-trips to the same IEEE-754 double."""
    s = repr(float(x))
    return s if any(c in s for c in ".eE") else s + ".0"


def render(data: dict) -> str:
    recs = data["records"]
    out = [
        "//! GENERATED by tools/gen_golden_rs.py; do not edit.",
        "//!",
        f"//! Source: {data['generator']} ({data['oracle']}). Each output",
        "//! carries its own absolute tolerance (see the JSON tolerance rules).",
        "",
        "#![allow(clippy::excessive_precision, clippy::unreadable_literal)]",
        "",
        CRATE_TYPES,
        "",
        "/// One golden record: inputs in the JSON schema order for `func`, and",
        "/// `(name, value, tolerance)` triples.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct GoldenRecord {",
        "    /// Function name in the JSON schema.",
        "    pub func: &'static str,",
        "    /// Inputs, zero padded.",
        f"    pub inputs: [f64; {MAX_IN}],",
        "    /// Option payoff direction.",
        "    pub option_type: OptionType,",
        "    /// Function-specific flag (CRR: 1 = American).",
        "    pub flag: i32,",
        "    /// Expected outputs: (name, value, absolute tolerance).",
        "    pub outputs: &'static [(&'static str, f64, f64)],",
        "}",
        "",
        "/// All golden records.",
        "pub const RECORDS: &[GoldenRecord] = &[",
    ]
    for r in recs:
        ins = list(r["in"]) + [0.0] * (MAX_IN - len(r["in"]))
        ot = "OptionType::Call" if r["type"] == "call" else "OptionType::Put"
        outs = ", ".join(f'("{k}", {fmt(v[0])}, {fmt(v[1])})' for k, v in r["out"].items())
        out.append(f'    GoldenRecord {{ func: "{r["fn"]}", inputs: [{", ".join(fmt(x) for x in ins)}], '
                   f'option_type: {ot}, flag: {r["flag"]}, outputs: &[{outs}] }},')
    out += ["];", ""]
    return "\n".join(out)


def main() -> int:
    check = "--check" in sys.argv[1:]
    args = [a for a in sys.argv[1:] if a != "--check"]
    json_path = Path(args[0]) if args else DEFAULT_JSON
    rs = Path(args[1]) if len(args) > 1 else DEFAULT_RS
    data = json.loads(json_path.read_text())
    if len(data["records"]) != data["n_records"]:
        raise SystemExit("n_records does not match the record list")
    text = render(data)
    if check:
        if not rs.exists() or rs.read_text() != text:
            print(f"STALE: {rs} differs from the golden JSON; rerun without --check")
            return 1
        print(f"OK: {rs} matches the golden JSON")
        return 0
    rs.write_text(text, newline="\n") if sys.version_info >= (3, 10) else rs.write_text(text)
    print(f"wrote {len(data['records'])} records to {rs}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
