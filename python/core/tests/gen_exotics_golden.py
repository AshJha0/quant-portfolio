"""Regenerate rust/core/tests/data/exotics_golden.txt from the Python pricers.

Run from the repo root:  python python/core/tests/gen_exotics_golden.py
The Rust test (rust/core/tests/exotics_parity.rs) holds every line to 1e-12
relative. test_exotics_golden_is_current checks the file is up to date.
"""

from __future__ import annotations

import itertools
import sys
from pathlib import Path

from qp_core.exotics.asian import (
    geometric_asian_price,
    turnbull_wakeman_continuous,
    turnbull_wakeman_price,
)
from qp_core.exotics.barriers import (
    barrier_price,
    double_knockout_price,
    double_no_touch,
    touch_price,
    vanilla_price,
)
from qp_core.vol.essvi import SVISlice, essvi_total_variance

GOLDEN = Path(__file__).resolve().parents[3] / "rust" / "core" / "tests" / "data" / "exotics_golden.txt"


def lines() -> list[str]:
    out = ["# name args... expected  (generated by python/core/tests/gen_exotics_golden.py)"]
    for cp, X, sig in itertools.product(("call", "put"), (90.0, 100.0, 110.0), (0.15, 0.3)):
        out.append(f"vanilla {cp} 100.0 {X!r} 0.75 0.05 0.02 {sig!r} {vanilla_price(cp, 100.0, X, 0.75, 0.05, 0.02, sig)!r}")
    for kind, cp, X, sig, reb in itertools.product(
        ("down_in", "down_out", "up_in", "up_out"), ("call", "put"), (90.0, 100.0, 110.0), (0.25, 0.3), (0.0, 3.0)
    ):
        H = 95.0 if kind.startswith("down") else 105.0
        p = barrier_price(kind, cp, 100.0, X, H, 0.5, 0.08, 0.04, sig, rebate=reb)
        out.append(f"barrier {kind} {cp} 100.0 {X!r} {H!r} 0.5 0.08 0.04 {sig!r} {reb!r} {p!r}")
    for kind, hit in itertools.product(("one_touch_down", "one_touch_up", "no_touch_down", "no_touch_up"), (0, 1)):
        if hit and kind.startswith("no"):
            continue
        H = 92.0 if kind.endswith("down") else 108.0
        p = touch_price(kind, 100.0, H, 0.7, 0.03, 0.01, 0.2, cash=2.5, pay_at_hit=bool(hit))
        out.append(f"touch {kind} 100.0 {H!r} 0.7 0.03 0.01 0.2 2.5 {hit} {p!r}")
    for cp, (L, U), sig in itertools.product(("call", "put"), ((50.0, 150.0), (80.0, 120.0), (90.0, 110.0)), (0.15, 0.35)):
        p = double_knockout_price(cp, 100.0, 100.0, L, U, 0.25, 0.1, 0.1, sig)
        out.append(f"dko {cp} 100.0 100.0 {L!r} {U!r} 0.25 0.1 0.1 {sig!r} {p!r}")
    for (L, U), sig in itertools.product(((85.0, 115.0), (95.0, 110.0)), (0.1, 0.2)):
        p = double_no_touch(100.0, L, U, 0.5, 0.03, 0.01, sig, cash=1.0, n_terms=50)
        out.append(f"dnt 100.0 {L!r} {U!r} 0.5 0.03 0.01 {sig!r} {p!r}")
    fix = [i / 12 for i in range(1, 13)]
    for cp, X in itertools.product(("call", "put"), (90.0, 100.0, 110.0)):
        g = geometric_asian_price(cp, 100.0, X, fix, 1.0, 0.05, 0.03, 0.25)
        tw = turnbull_wakeman_price(cp, 100.0, X, fix, 1.0, 0.05, 0.03, 0.25)
        twc = turnbull_wakeman_continuous(cp, 100.0, X, 1.0, 0.05, 0.03, 0.25, 0.25)
        out.append(f"geo {cp} 100.0 {X!r} 1.0 0.05 0.03 0.25 {g!r}")
        out.append(f"tw {cp} 100.0 {X!r} 1.0 0.05 0.03 0.25 {tw!r}")
        out.append(f"twc {cp} 100.0 {X!r} 1.0 0.05 0.03 0.25 0.25 {twc!r}")
    for k in (-0.5, -0.1, 0.0, 0.07, 0.6):
        out.append(f"essvi {k!r} 0.01 -0.35 0.12 {float(essvi_total_variance(k, 0.01, -0.35, 0.12))!r}")
        sv = SVISlice(0.004, 0.08, -0.4, 0.01, 0.15)
        out.append(f"svi {k!r} 0.004 0.08 -0.4 0.01 0.15 {float(sv.total_variance(k))!r}")
    return out


def _tok_equal(a: str, b: str, rtol: float) -> bool:
    if a == b:
        return True
    try:
        x, y = float(a), float(b)
    except ValueError:
        return False
    return abs(x - y) <= rtol * max(abs(x), abs(y), 1e-300)


def same_records(got: list[str], want: list[str], rtol: float = 1e-12) -> bool:
    """Line-by-line equality; numeric tokens may differ in the last bits.

    The fixtures are generated on one machine and checked on others; libm
    (erf, exp, log) can differ by an ulp or two across platforms, so numbers
    are compared to ``rtol`` relative, the same bound the Rust and C++
    parity tests apply. Labels and the line count must match exactly.
    """
    if len(got) != len(want):
        return False
    for g, w in zip(got, want, strict=True):
        gt, wt = g.split(), w.split()
        if len(gt) != len(wt) or not all(_tok_equal(x, y, rtol) for x, y in zip(gt, wt, strict=True)):
            return False
    return True


if __name__ == "__main__":
    text = "\n".join(lines()) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if same_records(text.splitlines(), GOLDEN.read_text().splitlines()) else 1)
    GOLDEN.write_text(text, newline="\n")
