"""The committed Rust/C++ parity fixture must equal what Python generates now."""

from __future__ import annotations

from pathlib import Path

from qp_core.xva import _parity


def _tok_equal(a: str, b: str, rtol: float) -> bool:
    if a == b:
        return True
    try:
        x, y = float(a), float(b)
    except ValueError:
        return False
    return abs(x - y) <= rtol * max(abs(x), abs(y), 1e-300)


def _same_records(got: list[str], want: list[str], rtol: float = 1e-12) -> bool:
    """Line-by-line equality; numeric tokens may differ in the last bits.

    The fixtures are generated on one machine and checked on others; libm
    (erf, exp, log) can differ by an ulp or two across platforms, so numbers
    are compared to ``rtol`` relative, the same bound the Rust and C++
    parity tests apply. Labels and the line count must match exactly.
    """
    if len(got) != len(want):
        return False
    for g, w in zip(got, want, strict=True):
        gt, wt = g.split(), w.split()
        if len(gt) != len(wt) or not all(_tok_equal(x, y, rtol) for x, y in zip(gt, wt, strict=True)):
            return False
    return True

FIXTURE = Path(__file__).resolve().parents[3] / "rust" / "core" / "tests" / "data" / "xva_capital_parity.txt"


def test_fixture_matches_python() -> None:
    want = FIXTURE.read_text(encoding="ascii").splitlines()
    got = ["# generated by python -m qp_core.xva._parity; do not edit", *_parity.records()]
    assert len(got) == len(want)
    bad = [(g, w) for g, w in zip(got, want, strict=True) if not _same_records([g], [w])]
    assert not bad, bad[:5]
