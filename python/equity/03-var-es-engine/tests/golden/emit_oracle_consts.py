#!/usr/bin/env python3
"""Emit the W5 oracle values as C++ and Rust constants.

Reads the two ``oracle_vectors.json`` files written by ``var_oracle.py``
and writes, for each engine,

* ``cpp/<engine>/tests/oracle_vectors.hpp`` (``namespace oracle``), and
* ``rust/<engine>/tests/oracle/mod.rs`` (upper-case ``pub const``).

Values are printed with Python's shortest round-trip ``repr``, which C++
and Rust parse back to the same double. ``--check`` fails if any emitted
file differs from what would be written now. Standard library only.

    python tests/golden/emit_oracle_consts.py [--check]
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
PROJECTS = {
    "equity": (HERE / "oracle_vectors.json", "equity-var-engine"),
    "fx": (ROOT / "python" / "fx" / "03-var-es-engine" / "tests" / "golden" / "oracle_vectors.json",
           "fx-var-engine"),
}
BANNER = ("GENERATED by python/equity/03-var-es-engine/tests/golden/emit_oracle_consts.py "
          "from the independent oracle (var_oracle.py: mpmath, exact rationals). Do not edit.")


def literal(x: float) -> str:
    if not math.isfinite(x):
        raise ValueError(f"non-finite oracle value {x!r}")
    s = repr(float(x))
    return s if any(c in s for c in ".e") else s + ".0"


def cpp(values: dict[str, float]) -> str:
    lines = [f"// {BANNER}", "#pragma once", "", "namespace oracle {", ""]
    lines += [f"inline constexpr double {k} = {literal(v)};" for k, v in sorted(values.items())]
    lines += ["", "}  // namespace oracle", ""]
    return "\n".join(lines)


def rust(values: dict[str, float]) -> str:
    lines = [f"//! {BANNER}", "#![allow(dead_code)]", ""]
    lines += [f"pub const {k.upper()}: f64 = {literal(v)};" for k, v in sorted(values.items())]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = 0
    for json_path, engine in PROJECTS.values():
        values = json.loads(json_path.read_text())["values"]
        for path, text in ((ROOT / "cpp" / engine / "tests" / "oracle_vectors.hpp", cpp(values)),
                           (ROOT / "rust" / engine / "tests" / "oracle" / "mod.rs", rust(values))):
            if check:
                if not path.exists() or path.read_text() != text:
                    print(f"stale: {path}")
                    stale += 1
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, newline="\n")
                print(f"wrote {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
