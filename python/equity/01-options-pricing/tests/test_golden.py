"""Golden vectors: the engine must match the mpmath oracle within per-output tolerances.

The JSON is generated by ``tests/golden/generate_golden.py`` from mpmath at
50 digits (not from this package). The C++ and Rust engines consume the
same file through their generated test modules.
"""

import json
import subprocess
import sys
from pathlib import Path

import pytest

from eq_options import bs_price
from eq_options._jsonl import handle

GOLDEN = Path(__file__).parent / "golden" / "golden_vectors.json"
DATA = json.loads(GOLDEN.read_text())


def _request(record: dict) -> dict:
    names = DATA["schema"][record["fn"]]["in"]
    req = dict(zip(names, record["in"]), fn=record["fn"], type=record["type"])
    if record["fn"] == "crr":
        req["american"] = bool(record["flag"])
    return req


def _evaluate(record: dict) -> dict:
    req = _request(record)
    if record["fn"] == "bs" and set(record["out"]) == {"price"}:
        return {"price": bs_price(req["S"], req["K"], req["T"], req["r"], req["sigma"],
                                  req["q"], req["type"])}
    return handle(req)


def test_coverage() -> None:
    fns = {r["fn"] for r in DATA["records"]}
    assert fns == {"bs", "iv", "crr", "b76"}
    assert len(DATA["records"]) == DATA["n_records"] >= 400
    assert any(set(r["out"]) >= {"vanna", "volga"} for r in DATA["records"])


@pytest.mark.parametrize("idx", range(DATA["n_records"]))
def test_record_matches_oracle(idx: int) -> None:
    record = DATA["records"][idx]
    got = _evaluate(record)
    for name, (expected, tol) in record["out"].items():
        assert abs(got[name] - expected) <= tol, (record, name, got[name])


def test_worst_deviation_is_well_inside_tolerance() -> None:
    """Track the worst dev/tol ratio so a drift from 1e-15 towards the
    tolerance is visible before it fails."""
    worst = 0.0
    for record in DATA["records"]:
        got = _evaluate(record)
        for name, (expected, tol) in record["out"].items():
            worst = max(worst, abs(got[name] - expected) / tol)
    assert worst <= 1.0
    print(f"worst deviation / tolerance = {worst:.3f}")


def test_generator_check_passes() -> None:
    gen = Path(__file__).parent / "golden" / "generate_golden.py"
    proc = subprocess.run([sys.executable, str(gen), "--check"], capture_output=True, text=True)
    assert proc.returncode == 0, proc.stdout + proc.stderr
