"""Generate the dated-bootstrap fixture from QuantLib (the independent oracle).

Run from the fixed-income project with QuantLib installed (``--group oracle``):

    python tests/oracle/gen_dated_bootstrap_fixture.py

It writes ``tests/data/dated_bootstrap_usd.txt``. The file holds, for three
bootstrap problems, every instrument as explicit periods (integer days from
the valuation date and accrual fractions, all taken from QuantLib's own
schedules and coupons) and the discount factors QuantLib's bootstrap puts on
each pillar. The Python, Rust and C++ bootstraps read the same file and must
land on QuantLib's numbers; they are never compared with each other only.

The quotes are ILLUSTRATIVE. They have the shape of the USD SOFR, a 3M term
index and the EURUSD basis curves around mid-2024, but they are not market
data and nothing here should be read as a 2024 market level.

Problems:

1. ``usd_ois``: SOFR overnight deposit, SOFR OIS (annual, ACT/360, payment
   lag 2 days), four 3M SOFR futures with a Hull-White convexity adjustment
   at a stated flat vol (a=0.03, sigma=0.0085; labelled assumption, computed
   by ``ql.HullWhite.convexityBias``), longer OIS.
2. ``term3m``: a 3M term index projection curve (deposit, FRAs, swaps with a
   semi-annual 30/360 fixed leg and a quarterly float leg), discounted on the
   ``usd_ois`` curve (QuantLib's exogenous discounting handle).
3. ``eur_xccy``: the EUR discount curve for USD-collateralised EUR cash flows,
   from constant-notional EURUSD 3M/3M basis swaps (spread on the EUR leg),
   given a EUR OIS projection curve and the ``usd_ois`` curve.
"""

from __future__ import annotations

import pathlib

import QuantLib as ql

OUT = pathlib.Path(__file__).resolve().parents[1] / "data" / "dated_bootstrap_usd.txt"

TODAY = ql.Date(28, 6, 2024)
A365 = ql.Actual365Fixed()
HW_A, HW_SIGMA = 0.03, 0.0085

OIS_SHORT = [("1W", 0.05330), ("1M", 0.05325), ("3M", 0.05300)]
FUTURES = [(9, 2024, 94.955), (12, 2024, 95.290), (3, 2025, 95.615), (6, 2025, 95.880)]
OIS_LONG = [("18M", 0.04640), ("2Y", 0.04480), ("3Y", 0.04200), ("4Y", 0.04050),
            ("5Y", 0.03960), ("7Y", 0.03880), ("10Y", 0.03860), ("15Y", 0.03870),
            ("20Y", 0.03850), ("30Y", 0.03700)]
TERM_DEP = 0.05420
TERM_FRAS = [(3, 0.05200), (6, 0.04880), (9, 0.04600)]
TERM_SWAPS = [(2, 0.04650), (3, 0.04360), (5, 0.04100), (7, 0.04010), (10, 0.03990),
              (15, 0.03990), (20, 0.03960), (30, 0.03800)]
EUR_ZERO = [(0.5, 0.0365), (1, 0.0340), (2, 0.0300), (5, 0.0270), (10, 0.0265),
            (20, 0.0262), (31, 0.0255)]
XCCY = [(1, -0.0008), (2, -0.0012), (3, -0.0015), (5, -0.0018), (7, -0.0019),
        (10, -0.0020)]


def day(d: ql.Date) -> int:
    return int(d - TODAY)


def bootstrap(helpers: list) -> ql.YieldTermStructure:
    curve = ql.PiecewiseLogLinearDiscount(TODAY, helpers, A365)
    curve.enableExtrapolation()
    curve.discount(1.0)  # force the bootstrap
    return curve


def coupons(leg):
    return [ql.as_coupon(cf) for cf in leg if ql.as_coupon(cf) is not None]


def fwd_line(s: ql.Date, e: ql.Date, rate: float, label: str) -> str:
    return f"fwd {day(s)} {day(e)} {ql.Actual360().yearFraction(s, e)!r} {rate!r}  # {label}"


def swap_lines(rate: float, fixed, floating, label: str) -> list[str]:
    fc, lc = coupons(fixed), coupons(floating)
    out = [f"swap {rate!r} {len(fc)} {len(lc)}  # {label}"]
    out += [f"f {day(c.date())} {c.accrualPeriod()!r}" for c in fc]
    out += [f"l {day(c.accrualStartDate())} {day(c.accrualEndDate())} {day(c.date())} "
            f"{c.accrualPeriod()!r}" for c in lc]
    return out


def expect_lines(curve, pillars) -> list[str]:
    return [f"expect {day(d)} {curve.discount(d)!r}" for d in pillars]


def main() -> None:
    ql.Settings.instance().evaluationDate = TODAY
    lines = [
        "# Dated-bootstrap fixture generated by tests/oracle/gen_dated_bootstrap_fixture.py",
        f"# QuantLib {ql.__version__}; valuation date {TODAY.ISO()}; days from valuation date;",
        "# curve time t = days/365 (ACT/365F); log-linear discount factors.",
        "# ILLUSTRATIVE QUOTES, NOT MARKET DATA.",
        f"# Futures convexity: Hull-White a={HW_A}, sigma={HW_SIGMA} (stated assumption).",
    ]

    # ---- 1. USD SOFR OIS -------------------------------------------------
    sofr = ql.Sofr()
    lines.append("build usd_ois discount=self projection=self")
    helpers, pillars, body = [], [], []
    dep = ql.DepositRateHelper(ql.QuoteHandle(ql.SimpleQuote(0.05335)), sofr)
    helpers.append(dep)
    body.append(fwd_line(dep.earliestDate(), dep.maturityDate(), 0.05335, "SOFR ON deposit"))

    def ois(tenor: str, rate: float) -> None:
        h = ql.OISRateHelper(2, ql.Period(tenor), ql.QuoteHandle(ql.SimpleQuote(rate)), sofr,
                             paymentLag=2, paymentFrequency=ql.Annual)
        helpers.append(h)
        sw = h.swap()
        body.extend(swap_lines(rate, sw.fixedLeg(), sw.overnightLeg(), f"SOFR OIS {tenor}"))

    for tenor, rate in OIS_SHORT:
        ois(tenor, rate)
    for month, year, price in FUTURES:
        start = ql.IMM.nextDate(ql.Date(1, month, year), False)
        end = ql.IMM.nextDate(start + ql.Period(3, ql.Months) - ql.Period(7, ql.Days), False)
        t1, t2 = A365.yearFraction(TODAY, start), A365.yearFraction(TODAY, end)
        conv = ql.HullWhite.convexityBias(price, t1, t2, HW_SIGMA, HW_A)
        h = ql.SofrFutureRateHelper(ql.QuoteHandle(ql.SimpleQuote(price)), month, year,
                                    ql.Quarterly, ql.QuoteHandle(ql.SimpleQuote(conv)))
        helpers.append(h)
        s, e = h.earliestDate(), h.maturityDate()
        fwd = (100.0 - price) / 100.0 - conv
        body.append(fwd_line(s, e, fwd, f"SOFR 3M future {month}/{year} price {price} conv {conv!r}"))
    for tenor, rate in OIS_LONG:
        ois(tenor, rate)
    usd = bootstrap(helpers)
    pillars = [h.pillarDate() for h in helpers]
    lines += body + expect_lines(usd, pillars) + ["end"]
    usd_handle = ql.YieldTermStructureHandle(usd)

    # ---- 2. 3M term index projection, OIS discounted ---------------------
    cal = ql.UnitedStates(ql.UnitedStates.FederalReserve)
    term = ql.IborIndex("TERM3M", ql.Period(3, ql.Months), 2, ql.USDCurrency(), cal,
                        ql.ModifiedFollowing, False, ql.Actual360())
    lines.append("build term3m discount=usd_ois projection=self")
    helpers, body = [], []
    h = ql.DepositRateHelper(ql.QuoteHandle(ql.SimpleQuote(TERM_DEP)), term)
    helpers.append(h)
    body.append(fwd_line(h.earliestDate(), h.maturityDate(), TERM_DEP, "TERM3M deposit"))
    for m, rate in TERM_FRAS:
        h = ql.FraRateHelper(ql.QuoteHandle(ql.SimpleQuote(rate)), m, term)
        helpers.append(h)
        body.append(fwd_line(h.earliestDate(), h.maturityDate(), rate, f"FRA {m}x{m + 3}"))
    for n, rate in TERM_SWAPS:
        h = ql.SwapRateHelper(ql.QuoteHandle(ql.SimpleQuote(rate)), ql.Period(n, ql.Years), cal,
                              ql.Semiannual, ql.ModifiedFollowing, ql.Thirty360(ql.Thirty360.BondBasis),
                              term, ql.QuoteHandle(), ql.Period(0, ql.Days), usd_handle)
        helpers.append(h)
        sw = h.swap()
        body.extend(swap_lines(rate, sw.fixedLeg(), sw.floatingLeg(), f"TERM3M swap {n}Y"))
    proj = bootstrap(helpers)
    lines += body + expect_lines(proj, [h.pillarDate() for h in helpers]) + ["end"]

    # ---- 3. EUR discount curve from EURUSD basis swaps -------------------
    eur_dates = [TODAY] + [TODAY + ql.Period(int(round(t * 12)), ql.Months) for t, _ in EUR_ZERO]
    eur_dfs = [1.0] + [float(ql.InterestRate(z, A365, ql.Continuous, ql.Annual).discountFactor(
        A365.yearFraction(TODAY, d))) for d, (_, z) in zip(eur_dates[1:], EUR_ZERO, strict=True)]
    eur_ois = ql.DiscountCurve(eur_dates, eur_dfs, A365)
    eur_ois.enableExtrapolation()
    lines.append("given eur_ois")
    lines += [f"node {day(d)} {x!r}" for d, x in zip(eur_dates[1:], eur_dfs[1:], strict=True)]
    lines.append("end")
    joint = ql.JointCalendar(ql.TARGET(), cal)
    eur_idx = ql.IborIndex("EURON3M", ql.Period(3, ql.Months), 2, ql.EURCurrency(), joint,
                           ql.ModifiedFollowing, False, ql.Actual360(),
                           ql.YieldTermStructureHandle(eur_ois))
    usd_idx = ql.IborIndex("USDON3M", ql.Period(3, ql.Months), 2, ql.USDCurrency(), joint,
                           ql.ModifiedFollowing, False, ql.Actual360(), usd_handle)
    lines.append("build eur_xccy discount=self projection=eur_ois domestic=usd_ois")
    helpers, body = [], []
    for n, basis in XCCY:
        h = ql.ConstNotionalCrossCurrencyBasisSwapRateHelper(
            ql.QuoteHandle(ql.SimpleQuote(basis)), ql.Period(n, ql.Years), 2, joint,
            ql.ModifiedFollowing, False, eur_idx, usd_idx, usd_handle, False, True)
        helpers.append(h)
        s0, en = h.earliestDate(), h.maturityDate()
        legs = [[c for c in (ql.as_floating_rate_coupon(cf) for cf in h.swap().leg(k)) if c]
                for k in range(2)]
        body.append(f"xbs {basis!r} {day(s0)} {day(en)} {len(legs[0])} {len(legs[1])}"
                    f"  # EURUSD basis {n}Y")
        for leg in legs:
            body += [f"l {day(c.accrualStartDate())} {day(c.accrualEndDate())} {day(c.date())} "
                     f"{c.accrualPeriod()!r}" for c in leg]
    eur = bootstrap(helpers)
    lines += body + expect_lines(eur, [h.pillarDate() for h in helpers]) + ["end"]

    # ---- Hull-White convexity cross-check points --------------------------
    lines.append("# hwconv price t1 t2 sigma a quantlib_bias")
    for price, t1, t2 in [(95.0, 0.25, 0.5), (96.0, 2.0, 2.25), (97.0, 9.75, 10.0)]:
        bias = ql.HullWhite.convexityBias(price, t1, t2, HW_SIGMA, HW_A)
        lines.append(f"hwconv {price!r} {t1!r} {t2!r} {HW_SIGMA!r} {HW_A!r} {bias!r}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
