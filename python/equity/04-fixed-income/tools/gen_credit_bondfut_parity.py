"""Write the Python reference values the Rust and C++ credit-index and
bond-futures kernels must reproduce (plan W18, decision D1).

Run from the repository root:

    python python/equity/04-fixed-income/tools/gen_credit_bondfut_parity.py

Output: ``rust/core/tests/data/credit_bondfut_parity.txt`` (shared by
``rust/core/tests/credit_bondfut_parity.rs`` and
``cpp/core/tests/test_credit_bondfut.cpp``). Floats use ``repr`` so they
round-trip exactly.

Lines:
  ``K coupon n z quarterly cf``                 CME conversion factor kernel
  ``R dirty invoice cash tau tau_c repo``       implied repo kernel
  ``N dirty cash tau tau_c repo ai fxcf net``   net basis kernel
  ``I recovery t_end t_cash prot rpv01 df``     ISDA legs, then lines
      ``H`` hazard times, ``h`` hazard rates, ``T`` discount times,
      ``Z`` zero rates, ``S`` accrual starts, ``E`` accrual ends,
      ``P`` payment times, ``F`` accrual fractions
  ``O nbonds sd fair option``                   delivery option, then per bond
      ``B freq accrued fwd_yield cf``, ``X`` exponents, ``W`` cash flows
"""

from __future__ import annotations

import pathlib
from datetime import date

from fi_rates.bond import FixedRateBond, _period_exponents
from fi_rates.bond_futures import (
    cme_cf_kernel,
    delivery_option_kernel,
    implied_repo_kernel,
    net_basis_kernel,
)
from qp_core.credit_index.isda import (
    CdsContract,
    FlatForwardCurve,
    HazardCurve,
    bootstrap_hazard,
    isda_legs_kernel,
)

OUT = pathlib.Path("rust/core/tests/data/credit_bondfut_parity.txt")


def _row(tag: str, xs) -> str:
    return tag + " " + " ".join(repr(float(x)) for x in xs)


def main() -> None:
    lines = ["# generated by python/equity/04-fixed-income/tools/gen_credit_bondfut_parity.py"]
    for c in (0.0, 0.01125, 0.0275, 0.045, 0.06, 0.08, 0.1):
        for n in (0, 1, 4, 9, 18, 29):
            for z in (0, 2, 3, 6, 7, 9, 11):
                for q in (True, False):
                    lines.append(f"K {c!r} {n} {z} {int(q)} {cme_cf_kernel(c, n, z, q)!r}")
    for dirty, inv, cash, tau, tau_c in [(103.1, 104.0, 0.0, 0.3, 0.0),
                                         (101.7, 99.2, 2.875, 0.29, 0.06),
                                         (131.9, 130.0, 4.5, 0.5, 0.25)]:
        r = implied_repo_kernel(dirty, inv, cash, tau, tau_c)
        lines.append(_row("R", (dirty, inv, cash, tau, tau_c, r)))
        for repo in (0.0, 0.0624, r):
            nb = net_basis_kernel(dirty, cash, tau, tau_c, repo, 1.1, inv - 1.1)
            lines.append(_row("N", (dirty, cash, tau, tau_c, repo, 1.1, inv - 1.1, nb)))

    t0 = date(2009, 5, 21)
    disc = FlatForwardCurve((0.0958904109589041, 1.010958904109589, 5.016438356164383,
                             10.021917808219179, 30.03013698630137),
                            (0.0031233773559633366, 0.01544604999250054, 0.02458221884142598,
                             0.03348840999666881, 0.038564319399313964))
    curves = [
        HazardCurve((50.0,), (0.0,)),
        HazardCurve((50.0,), (0.02,)),
        bootstrap_hazard(t0, [date(2010, 6, 20), date(2014, 6, 20), date(2019, 6, 20)],
                         [0.004, 0.012, 0.015], disc, 0.4),
        bootstrap_hazard(t0, [date(2011, 6, 20)], [0.1], disc, 0.2),
    ]
    for hz in curves:
        for mat, rec in [(date(2010, 6, 20), 0.4), (date(2014, 6, 20), 0.25), (date(2019, 6, 20), 0.4)]:
            k = CdsContract(t0, mat, 0.01, rec).kernel_inputs()
            prot, rpv, df = isda_legs_kernel(hz.times, hz.rates, disc.times, disc.zero_rates, rec,
                                             k["t_end"], k["acc_start"], k["acc_end"],
                                             k["pay_time"], k["acc_frac"], k["t_cash"])
            lines.append(_row("I", (rec, k["t_end"], k["t_cash"], prot, rpv, df)))
            for tag, xs in (("H", hz.times), ("h", hz.rates), ("T", disc.times),
                            ("Z", disc.zero_rates), ("S", k["acc_start"]), ("E", k["acc_end"]),
                            ("P", k["pay_time"]), ("F", k["acc_frac"])):
                lines.append(_row(tag, xs))

    deliv = date(2026, 12, 31)
    bonds = [FixedRateBond(date(2015, 8, 15), date(2033, 8, 15), 0.0275, 2, "ACT/ACT-ICMA"),
             FixedRateBond(date(2015, 2, 15), date(2034, 2, 15), 0.04, 2, "ACT/ACT-ICMA"),
             FixedRateBond(date(2015, 11, 15), date(2035, 11, 15), 0.045, 2, "ACT/ACT-ICMA")]
    ex, fl = [], []
    for b in bonds:
        e, f = _period_exponents(b, deliv)
        ex.append([float(x) for x in e])
        fl.append([float(x) for x in f])
    acc = [1.3, 1.2, 0.5]
    for ys, cfs, sd in [((0.041, 0.042, 0.043), (0.8571, 0.9369, 0.9617), 0.0),
                        ((0.041, 0.042, 0.043), (0.8571, 0.9369, 0.9617), 0.003),
                        ((0.035, 0.05, 0.06), (0.8, 0.95, 1.0), 0.01)]:
        fair, opt = delivery_option_kernel(ex, fl, acc, [2, 2, 2], ys, cfs, sd)
        lines.append(_row("O", (3, sd, fair, opt)))
        for i in range(3):
            lines.append(_row("B", (2, acc[i], ys[i], cfs[i])))
            lines.append(_row("X", ex[i]))
            lines.append(_row("W", fl[i]))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
