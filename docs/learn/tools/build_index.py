"""Write docs/learn/L0..L4/QUESTIONS.md from the level tags in docs/LEARN.md.

The question bank stays in one file (``docs/LEARN.md``, the appendix) so that
links into it from other documents keep working. Each level folder gets a
generated list of the questions tagged with that level, grouped by set.

Run ``python docs/learn/tools/build_index.py`` after editing LEARN.md;
``python docs/learn/tools/build_index.py --check`` exits 1 if a generated file
is stale (the test suite runs the check).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from lint_learn import LEARN, SET, TAGS, split_questions

LEARN_DIR = LEARN.parent / "learn"
LEVEL_TAG = re.compile(r"`(L[0-4])`")
HEADER = """# {level} questions

Generated by `docs/learn/tools/build_index.py` from the level tags in
[LEARN.md](../../LEARN.md). Do not edit by hand. Open the appendix and search
for the question number within its set, for example `Set 3` then `**Q4.`.

{count} questions at this level.
"""


def _set_titles(lines: list[str]) -> dict[int, str]:
    out: dict[int, str] = {}
    for line in lines:
        if (m := SET.match(line)) is not None:
            out[int(m.group(1))] = line.split(":", 1)[1].strip()
    return out


def render() -> dict[Path, str]:
    lines = LEARN.read_text(encoding="utf-8").splitlines()
    titles = _set_titles(lines)
    by_level: dict[str, list[tuple[int, int, str]]] = {f"L{k}": [] for k in range(5)}
    for q in split_questions(lines):
        tag_line = next(t for t in q.text if TAGS.match(t))
        m = LEVEL_TAG.search(tag_line)
        if m is None:
            continue
        title = q.text[0].removeprefix("**").split("**")[0]
        title = re.sub(r"^Q\d+\.\s*", "", title)
        by_level[m.group(1)].append((q.set_no, q.number, title))
    files: dict[Path, str] = {}
    for level, items in by_level.items():
        parts = [HEADER.format(level=level, count=len(items))]
        current = 0
        for set_no, number, title in items:
            if set_no != current:
                current = set_no
                parts.append(f"\n## Set {set_no}: {titles[set_no]}\n")
            parts.append(f"- Q{number}. {title}")
        files[LEARN_DIR / level / "QUESTIONS.md"] = "\n".join(parts) + "\n"
    return files


def main(argv: list[str]) -> int:
    stale = []
    for path, text in render().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if "--check" not in argv:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if "--check" in argv and stale:
        for p in stale:
            print(f"stale: {p}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
